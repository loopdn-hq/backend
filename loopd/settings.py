# Channels
# https://channels.readthedocs.io/en/latest/topics/channel_layers.html
#
# The channel layer is how one worker tells the others that a message
# arrived. Redis is the real implementation - staging already runs one. The
# in-memory layer is per-process, so it works for `runserver` and tests and
# silently drops cross-process events anywhere else.

